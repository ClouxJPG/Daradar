    function addLayer() {

        if (
            layer ||
            !map
        )
            return;

        const ui =
            makeSvg();

        layer = {
            svg:
                ui.svg,

            path:
                ui.path,

            pointsGroup:
                ui.pointsGroup
        };

        /*
           overlayPane — нормальный Leaflet pane.

           SVG физически находится внутри карты,
           а не поверх страницы.
        */

        map
            .getPanes()
            .overlayPane
            .appendChild(
                layer.svg
            );

        map.on(
            "move zoom resize",
            render
        );

        render();
    }

    /* =====================================================
       УДАЛЕНИЕ
       ===================================================== */

    function removeLayer() {

        if (!layer)
            return;

        if (map) {

            map.off(
                "move zoom resize",
                render
            );
        }

        if (
            layer.svg &&
            layer.svg.parentNode
        ) {

            layer.svg.parentNode.removeChild(
                layer.svg
            );
        }

        layer = null;
    }

    /* =====================================================
       ВИДИМОСТЬ
       ===================================================== */

    function setVisible(v) {

        visible = !!v;

        map =
            getMap();

        if (!map) {

            setTimeout(
                function () {

                    if (visible)
                        setVisible(true);

                },
                0
            );

            return;
        }

        if (visible) {

            addLayer();
            render();

        } else {

            removeLayer();
        }
    }

    /* =====================================================
       UPDATE

       index.html уже вызывает:
       RadarPoints.update()
       при moveend/resize.
       ===================================================== */

    function update() {

        if (!visible)
            return;

        const m =
            getMap();

        if (!m)
            return;

        if (m !== map) {

            removeLayer();

            map = m;
        }

        if (!layer)
            addLayer();

        render();
    }

