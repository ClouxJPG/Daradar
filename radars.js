    function render() {

        if (
            !layer ||
            !map
        )
            return;

        const size =
            map.getSize();

        layer.svg.setAttribute(
            "width",
            size.x
        );

        layer.svg.setAttribute(
            "height",
            size.y
        );

        layer.svg.setAttribute(
            "viewBox",
            "0 0 " +
            size.x +
            " " +
            size.y
        );

        /* -----------------------------------------------
           Покрытие
           ----------------------------------------------- */

        let d = "";

        for (
            const ring of COVERAGE
        ) {

            if (!ring.length)
                continue;

            const first =
                project(
                    map,
                    ring[0][0],
                    ring[0][1]
                );

            d +=
                "M" +
                first.x.toFixed(2) +
                " " +
                first.y.toFixed(2);

            for (
                let i = 1;
                i < ring.length;
                i++
            ) {

                const p =
                    project(
                        map,
                        ring[i][0],
                        ring[i][1]
                    );

                d +=
                    " L" +
                    p.x.toFixed(2) +
                    " " +
                    p.y.toFixed(2);
            }

            d += " Z ";
        }

        layer.path.setAttribute(
            "d",
            d
        );

        /* -----------------------------------------------
           Точки РЛС
           ----------------------------------------------- */

        while (
            layer.pointsGroup.firstChild
        ) {

            layer.pointsGroup.removeChild(
                layer.pointsGroup.firstChild
            );
        }

        for (
            let i = 0;
            i < RADARS.length;
            i++
        ) {

            const r =
                RADARS[i];

            const p =
                project(
                    map,
                    r.x,
                    r.y
                );

            const c =
                document.createElementNS(
                    "http://www.w3.org/2000/svg",
                    "circle"
                );

            c.setAttribute(
                "cx",
                p.x.toFixed(2)
            );

            c.setAttribute(
                "cy",
                p.y.toFixed(2)
            );

            /*
               Белый круг + чёрная обводка.

               Чёрной точки внутри НЕТ.
            */

            c.setAttribute(
                "r",
                "6.5"
            );

            c.setAttribute(
                "fill",
                "#fff"
            );

            c.setAttribute(
                "stroke",
                "#000"
            );

            c.setAttribute(
                "stroke-width",
                "2"
            );

            c.style.pointerEvents =
                "auto";

            c.style.cursor =
                "pointer";

            c.addEventListener(
                "click",
                function (e) {

                    e.preventDefault();
                    e.stopPropagation();

                    L.popup({
                        closeButton: true,
                        autoPan: true
                    })
                    .setLatLng(
                        frameToLatLng(
                            r.x,
                            r.y
                        )
                    )
                    .setContent(
                        "<b>РЛС</b><br>" +
                        "Положение восстановлено " +
                        "из кадра МЕТЕОРАД.<br>" +
                        "X: " +
                        r.x +
                        " &nbsp; Y: " +
                        r.y
                    )
                    .openOn(map);
                }
            );

            layer.pointsGroup.appendChild(
                c
            );
        }
    }

